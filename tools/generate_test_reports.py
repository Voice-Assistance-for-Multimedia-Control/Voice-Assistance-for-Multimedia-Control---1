"""
Generate the automated test reports in docs/reports/.

Runs the whole test suite once with line and branch coverage, then writes:

  docs/reports/unit-test-report.md        results per test file and per test
  docs/reports/unit-test-results.xml      the same results in JUnit XML
  docs/reports/code-coverage-report.md    statement (line) coverage per file
  docs/reports/branch-coverage-report.md  branch coverage per file
  docs/reports/coverage.xml               Cobertura XML (line + branch)
  docs/reports/coverage-html/index.html   browsable coverage report

docs/reports/system-validation-report.md (live system tests) is written by hand
and is not touched.

Usage (from the repository root, with the dev extras installed):

    pip install -e ".[dev]" selenium
    python tools/generate_test_reports.py
"""

import json
import platform
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import OrderedDict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reports"
SOURCES = ["src/voice_control", "media_controls", "main"]
GENERATED = ["unit-test-report.md", "unit-test-results.xml", "code-coverage-report.md",
             "branch-coverage-report.md", "coverage.xml", "coverage.json"]

# What each test file verifies (user story / requirement), for the unit report.
TEST_FILES = OrderedDict([
    ("test_tc01_wake_word.py", "TC-01, FR-1: wake word opens the listening window (US-01)"),
    ("test_sprint1_integration.py", "FR-2 to FR-9: all seven commands end to end through VoiceAssistant (US-01 to US-07)"),
    ("test_media_controls.py", "FR-2 to FR-8: media_controls functions (US-02 to US-07)"),
    ("test_player_controls.py", "FR-2 to FR-4: YouTube player play / pause / resume (US-02 to US-04)"),
    ("test_tc10_security_gating.py", "TC-10, SR-1: no action without the wake word"),
    ("test_security_validator.py", "SO-1, SR-1: session token and confidence checks"),
    ("test_audio_buffer.py", "SR-2: in-memory rolling buffer only"),
    ("test_transcriber.py", "SR-2, NFR-2: Vosk (local) and Google recognizers"),
    ("test_us09_feedback.py", "FR-10: command feedback (US-09)"),
    ("test_us13_mic_error_handling.py", "Microphone error handling (US-13)"),
    ("test_us15_recovery.py", "Recovery from recognition errors (US-15)"),
    ("test_us16_mute_and_timing.py", "Microphone privacy control (US-16) and NFR-1 timing log (US-11)"),
    ("test_us18_startup_check.py", "Startup system check (US-18)"),
    ("test_us19_status_and_us17_local.py", "Listening status indicator (US-19) and local processing (US-17, SR-2)"),
])

# Files that need real hardware or a real browser; their uncovered lines are
# verified by the live tests in docs/test-log.md instead.
LIVE_ONLY = {
    "src/voice_control/youtube_player.py": "Opens a real Chrome window; covered by live command tests (test log, US-14).",
    "src/voice_control/audio/capture.py": "Hardware microphone thread; covered by live tests (US-13, US-16) and the 2-hour run (US-10).",
    "src/voice_control/recognition/transcriber.py": "Loading a real Vosk model / Google API; covered by live accuracy tests (US-11).",
    "src/voice_control/runtime.py": "The live microphone loop run(); covered by live tests and the 2-hour run (US-10).",
    "main.py": "Program start-up with a real recognizer and Chrome; covered by live start-up checks (US-18).",
}


def pct(part, whole):
    return 100.0 * part / whole if whole else 100.0


def run_suite():
    # Remove only the generated files; hand-written reports in the folder are kept.
    OUT.mkdir(parents=True, exist_ok=True)
    shutil.rmtree(OUT / "coverage-html", ignore_errors=True)
    for name in GENERATED:
        (OUT / name).unlink(missing_ok=True)
    cmd = [sys.executable, "-m", "pytest", "tests", "-q", "-p", "no:cacheprovider",
           "--junitxml", str(OUT / "unit-test-results.xml"), "--cov-branch",
           "--cov-report", "xml:" + str(OUT / "coverage.xml"),
           "--cov-report", "json:" + str(OUT / "coverage.json"),
           "--cov-report", "html:" + str(OUT / "coverage-html")]
    for source in SOURCES:
        cmd += ["--cov", source]
    result = subprocess.run(cmd, cwd=ROOT)
    (OUT / "coverage-html" / ".gitignore").unlink(missing_ok=True)
    # Keep the XML independent of where the repository was checked out.
    xml_path = OUT / "coverage.xml"
    if xml_path.exists():
        xml_path.write_text(xml_path.read_text(encoding="utf-8").replace(str(ROOT), "."), encoding="utf-8")
    return result.returncode


def header(title):
    return [
        f"# {title}",
        "",
        "Voice Assistance for Multimedia Control. Generated by `tools/generate_test_reports.py`.",
        "",
        f"- Date: {date.today().isoformat()}",
        f"- Python {platform.python_version()} on {platform.system()}; the same suite runs in "
        "GitHub Actions on Python 3.9 and 3.12 for every push and pull request.",
        "- Tests use synthetic audio, a scripted recognizer and a fake media player, so they check the "
        "logic of the pipeline. Microphone accuracy and real YouTube playback are checked by the live "
        "system tests in [`docs/test-log.md`](../test-log.md).",
        "",
    ]


def unit_report():
    root = ET.parse(OUT / "unit-test-results.xml").getroot()
    suites = [root] if root.tag == "testsuite" else list(root)
    per_file = OrderedDict((name, []) for name in TEST_FILES)
    totals = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0, "time": 0.0}
    for suite in suites:
        totals["time"] += float(suite.get("time", 0))
        for case in suite.iter("testcase"):
            parts = case.get("classname", "").split(".")
            module = next((part for part in parts if part.startswith("test_")), parts[-1])
            test_name = case.get("name")
            if parts and parts[-1].startswith("Test"):
                test_name = f"{parts[-1]}::{test_name}"
            name = module + ".py"
            outcome = "PASS"
            if case.find("failure") is not None:
                outcome = "FAIL"
            elif case.find("error") is not None:
                outcome = "ERROR"
            elif case.find("skipped") is not None:
                outcome = "SKIPPED"
            totals["tests"] += 1
            totals["failures"] += outcome == "FAIL"
            totals["errors"] += outcome == "ERROR"
            totals["skipped"] += outcome == "SKIPPED"
            per_file.setdefault(name, []).append((test_name, outcome))

    passed = totals["tests"] - totals["failures"] - totals["errors"] - totals["skipped"]
    lines = header("Unit Test Report")
    lines += [
        "## Summary",
        "",
        "| Tests run | Passed | Failed | Errors | Skipped | Time |",
        "|---:|---:|---:|---:|---:|---:|",
        f"| {totals['tests']} | {passed} | {totals['failures']} | {totals['errors']} | "
        f"{totals['skipped']} | {totals['time']:.1f} s |",
        "",
        "**Result: " + ("PASS (all tests passed)" if passed == totals["tests"] else "FAIL") + "**",
        "",
        "## Results per test file",
        "",
        "| Test file | What it verifies | Tests | Passed |",
        "|---|---|---:|---:|",
    ]
    for name, cases in per_file.items():
        ok = sum(1 for _, outcome in cases if outcome == "PASS")
        lines.append(f"| `tests/{name}` | {TEST_FILES.get(name, '')} | {len(cases)} | {ok} |")
    lines += ["", "## Every test", ""]
    for name, cases in per_file.items():
        lines += [f"### `tests/{name}`", "", "| Test | Result |", "|---|---|"]
        lines += [f"| `{test}` | {outcome} |" for test, outcome in cases]
        lines.append("")
    lines += ["Machine-readable results: [`unit-test-results.xml`](unit-test-results.xml) (JUnit XML).", ""]
    (OUT / "unit-test-report.md").write_text("\n".join(lines), encoding="utf-8")
    return totals, passed


def coverage_reports():
    data = json.loads((OUT / "coverage.json").read_text(encoding="utf-8"))
    files = sorted(data["files"].items())
    t = data["totals"]

    # Statement (line) coverage
    lines = header("Code Coverage Report (Statement Coverage)")
    lines += [
        "## Summary",
        "",
        "| Statements | Covered | Missed | Statement coverage |",
        "|---:|---:|---:|---:|",
        f"| {t['num_statements']} | {t['covered_lines']} | {t['missing_lines']} | "
        f"**{pct(t['covered_lines'], t['num_statements']):.1f}%** |",
        "",
        "Combined line + branch coverage (coverage.py total): "
        f"**{t['percent_covered']:.1f}%**. Branch details: [`branch-coverage-report.md`](branch-coverage-report.md). "
        "Browsable report with highlighted lines: [`coverage-html/index.html`](coverage-html/index.html) "
        "(download the folder and open the file in a browser).",
        "",
        "## Per file",
        "",
        "| File | Statements | Missed | Coverage | Missing lines |",
        "|---|---:|---:|---:|---|",
    ]
    for path, info in files:
        s = info["summary"]
        missing = info.get("missing_lines", [])
        shown = ", ".join(str(n) for n in missing[:25]) + (" ..." if len(missing) > 25 else "")
        lines.append(f"| `{path}` | {s['num_statements']} | {s['missing_lines']} | "
                     f"{pct(s['covered_lines'], s['num_statements']):.0f}% | {shown or '-'} |")
    lines += _live_only_notes(files)
    (OUT / "code-coverage-report.md").write_text("\n".join(lines), encoding="utf-8")

    # Branch coverage
    lines = header("Branch Coverage Report")
    lines += [
        "Each `if`, loop and `try` creates two or more branches (for example, condition true and condition "
        "false). A branch is covered when at least one test takes it. *Partial* counts decision points where "
        "only some of the branches were taken.",
        "",
        "## Summary",
        "",
        "| Branches | Covered | Missed | Partial decision points | Branch coverage |",
        "|---:|---:|---:|---:|---:|",
        f"| {t['num_branches']} | {t['covered_branches']} | {t['missing_branches']} | "
        f"{t['num_partial_branches']} | **{pct(t['covered_branches'], t['num_branches']):.1f}%** |",
        "",
        "## Per file",
        "",
        "| File | Branches | Covered | Missed | Partial | Branch coverage |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for path, info in files:
        s = info["summary"]
        if not s["num_branches"]:
            lines.append(f"| `{path}` | 0 | - | - | - | n/a (no branches) |")
            continue
        lines.append(f"| `{path}` | {s['num_branches']} | {s['covered_branches']} | {s['missing_branches']} | "
                     f"{s['num_partial_branches']} | {pct(s['covered_branches'], s['num_branches']):.0f}% |")
    lines += ["", "## Branches not taken by the unit tests", "",
              "Shown as `line -> destination line` (a destination of `-1` means leaving the function).", ""]
    for path, info in files:
        missing = info.get("missing_branches", [])
        if missing:
            shown = ", ".join(f"{a}->{b}" for a, b in missing[:30]) + (" ..." if len(missing) > 30 else "")
            lines.append(f"- `{path}`: {shown}")
    lines += _live_only_notes(files)
    (OUT / "branch-coverage-report.md").write_text("\n".join(lines), encoding="utf-8")
    (OUT / "coverage.json").unlink()
    return t


def _live_only_notes(files):
    present = dict(files)
    notes = ["", "## Why some files are lower", "",
             "These parts need a real microphone, a real speech model or a real Chrome window, which the "
             "automated tests replace with fakes. They are verified by the live system tests instead:", "",
             "| File | Coverage | Verified instead by |", "|---|---:|---|"]
    for path, reason in LIVE_ONLY.items():
        if path in present:
            s = present[path]["summary"]
            notes.append(f"| `{path}` | {s['percent_covered']:.0f}% | {reason} |")
    notes.append("")
    return notes


def main():
    code = run_suite()
    totals, passed = unit_report()
    t = coverage_reports()
    print(f"\nReports written to {OUT.relative_to(ROOT)}: {passed}/{totals['tests']} tests passed, "
          f"statement coverage {pct(t['covered_lines'], t['num_statements']):.1f}%, "
          f"branch coverage {pct(t['covered_branches'], t['num_branches']):.1f}%")
    return code


if __name__ == "__main__":
    sys.exit(main())
